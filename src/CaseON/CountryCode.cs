/// <summary>
/// Immutable reference data for a country: names, ISO codes, international calling code, currency
/// and (where defined) a postal-code pattern.
/// </summary>
/// <param name="Code">The <see cref="CountryCode"/> identifier.</param>
/// <param name="Name">The English short name.</param>
/// <param name="Alpha2">The ISO 3166-1 alpha-2 code (e.g. <c>US</c>).</param>
/// <param name="Alpha3">The ISO 3166-1 alpha-3 code (e.g. <c>USA</c>).</param>
/// <param name="CallingCode">The ITU-T E.164 country calling code (e.g. <c>1</c> for the United States).</param>
/// <param name="CurrencyCode">The ISO 4217 currency code, or <see langword="null"/> if not applicable.</param>
/// <param name="PostalCodePattern">A regular expression matching valid postal codes, or <see langword="null"/> if the country has no postal-code system or no defined pattern.</param>
public sealed record CountryInfo(
    CountryCode Code,
    string Name,
    string Alpha2,
    string Alpha3,
    int CallingCode,
    string? CurrencyCode,
    string? PostalCodePattern);
